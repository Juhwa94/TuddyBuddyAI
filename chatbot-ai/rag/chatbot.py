def rag_answer(question: str, user_type: str = "GUEST") -> dict:
    question = question.strip()
    user_type = user_type.strip().upper()

    # 빈 질문은 PDF 검색이나 AI 호출 없이 안내
    if not question:
        return {
            "answer": (
                "**질문 내용 확인**\n\n"
                "기능명과 궁금한 내용을 함께 입력해 주세요. "
            )
        }
        
    # 비회원은 질문 내용을 먼저 검사
    if user_type != "MEMBER":
        guest_reply = get_guest_reply(question)
        
        if guest_reply is not None:
            return {"answer": guest_reply}
    
    # 기존 검색 범위 유지
    # MEMBER: COMMON + MEMBER
    # 그 외: COMMON
    docs = search_documents(
        query=question,
        k=3,
        user_type=user_type
    )

    # 검색된 문서 내용 결합
    if docs:
        context = "\n\n".join(
            doc.page_content for doc in docs
        )
    else:
        # 검색 결과가 없어도 AI가 질문의 모호함을 판단하도록 전달
        context = "검색된 안내 문서가 없습니다."

    # 질문 확인과 문서 기반 답변 생성을 한 번의 AI 호출로 처리
    answer = chain.invoke({
        "context": context,
        "question": question,
        "user_type": user_type
    })

    # 출처 없이 답변만 반환
    return {"answer": answer}


